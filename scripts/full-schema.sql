CREATE TABLE PERSON (
    PERSONID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LASTNAME VARCHAR2(50) NOT NULL,
    FIRSTNAME VARCHAR2(100) NOT NULL,
    MIDDLENAME VARCHAR2(30),
    DATEOFBIRTH DATE
);

CREATE TABLE DISCIPLINARYSTATUS (
    DISCIPLINARYSTATUSID NUMBER PRIMARY KEY,
    STATUS VARCHAR2(255),
    DESCRIPTION VARCHAR2(4000)
);

CREATE TABLE DISCIPLINARYACTION (
    ACTIONID NUMBER PRIMARY KEY,
    ACTION VARCHAR2(255),
    DESCRIPTION VARCHAR2(4000)
);

CREATE TABLE OFFENSE (
    OFFENSEID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OFFENSE VARCHAR2(255),
    TYPE VARCHAR2(255),
    DESCRIPTION VARCHAR2(4000)
);

CREATE TABLE SUGGESTION (
    SUGGESTIONID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TYPE VARCHAR2(255),
    SUGGESTIONTEXT CLOB
);

-- One chunk (heading + body) of a department's Student Handbook, ingested at
-- app startup from src/main/resources/handbook/*.md by HandbookSeeder. Used
-- as retrieval context for the student chatbot (ChatServiceImpl), scoped by
-- DEPARTMENT so a student only ever gets their own department's rules back.
CREATE TABLE HANDBOOKSECTION (
    HANDBOOKSECTIONID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DEPARTMENT VARCHAR2(20) NOT NULL,
    TITLE VARCHAR2(500),
    BODY CLOB,
    ORDERINDEX NUMBER
);

CREATE TABLE STUDENT (
    STUDENTID VARCHAR2(20) PRIMARY KEY,
    PERSONID NUMBER,
    ADDRESS VARCHAR2(255),
    STUDENTTYPE VARCHAR2(255),
    CONTACTNUMBER VARCHAR2(20),
    DEPARTMENT VARCHAR2(20),
    CONSTRAINT FK_STUDENT_PERSON FOREIGN KEY (PERSONID) REFERENCES PERSON (PERSONID)
);

CREATE TABLE GUARDIAN (
    GUARDIANID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PERSONID NUMBER,
    CONTACTNUMBER VARCHAR2(20),
    RELATIONSHIP VARCHAR2(50),
    CONSTRAINT FK_GUARDIAN_PERSON FOREIGN KEY (PERSONID) REFERENCES PERSON (PERSONID)
);

CREATE TABLE EMPLOYEE (
    EMPLOYEEID VARCHAR2(20) PRIMARY KEY,
    PERSONID NUMBER,
    DEPARTMENT VARCHAR2(20),
    EMPLOYEEROLE VARCHAR2(50),
    CONSTRAINT FK_EMPLOYEE_PERSON FOREIGN KEY (PERSONID) REFERENCES PERSON (PERSONID)
);

CREATE TABLE LOGIN (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(100) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(255) NOT NULL,
    JOIN_DATE TIMESTAMP NOT NULL,
    LAST_LOGIN_DATE TIMESTAMP,
    ROLE VARCHAR2(30) NOT NULL,
    AUTHORITIES VARCHAR2(255),
    IS_ACTIVE NUMBER(1) NOT NULL,
    IS_LOCKED NUMBER(1) NOT NULL,
    PERSONID NUMBER,
    CONSTRAINT FK_LOGIN_PERSON FOREIGN KEY (PERSONID) REFERENCES PERSON (PERSONID)
);

CREATE TABLE STUDENTGUARDIAN (
    STUDENTID VARCHAR2(20) NOT NULL,
    GUARDIANID NUMBER NOT NULL,
    CONSTRAINT PK_STUDENTGUARDIAN PRIMARY KEY (STUDENTID, GUARDIANID),
    CONSTRAINT FK_STUDENTGUARDIAN_STUDENT FOREIGN KEY (STUDENTID) REFERENCES STUDENT (STUDENTID),
    CONSTRAINT FK_STUDENTGUARDIAN_GUARDIAN FOREIGN KEY (GUARDIANID) REFERENCES GUARDIAN (GUARDIANID)
);

CREATE TABLE ENROLLMENT (
    ENROLLMENTID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENTID VARCHAR2(20),
    SCHOOLYEAR VARCHAR2(20),
    STUDENTLEVEL VARCHAR2(50),
    SECTION VARCHAR2(50),
    DEPARTMENT VARCHAR2(20),
    DISCIPLINARYSTATUSID NUMBER,
    CONSTRAINT FK_ENROLLMENT_STUDENT FOREIGN KEY (STUDENTID) REFERENCES STUDENT (STUDENTID),
    CONSTRAINT FK_ENROLLMENT_DISCSTATUS FOREIGN KEY (DISCIPLINARYSTATUSID) REFERENCES DISCIPLINARYSTATUS (DISCIPLINARYSTATUSID)
);

CREATE TABLE RECORD (
    RECORDID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENROLLMENTID NUMBER,
    EMPLOYEEID VARCHAR2(20),
    OFFENSEID NUMBER,
    DATEOFVIOLATION DATE,
    ACTIONID NUMBER,
    DATEOFRESOLUTION DATE,
    REMARKS VARCHAR2(500),
    STATUS VARCHAR2(20),
    CONSTRAINT FK_RECORD_ENROLLMENT FOREIGN KEY (ENROLLMENTID) REFERENCES ENROLLMENT (ENROLLMENTID),
    CONSTRAINT FK_RECORD_EMPLOYEE FOREIGN KEY (EMPLOYEEID) REFERENCES EMPLOYEE (EMPLOYEEID),
    CONSTRAINT FK_RECORD_OFFENSE FOREIGN KEY (OFFENSEID) REFERENCES OFFENSE (OFFENSEID),
    CONSTRAINT FK_RECORD_ACTION FOREIGN KEY (ACTIONID) REFERENCES DISCIPLINARYACTION (ACTIONID)
);

CREATE TABLE DOCUMENT (
    DOCUMENTID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENTID VARCHAR2(20),
    EXTRACTEDTEXT CLOB,
    CONSTRAINT FK_DOCUMENT_STUDENT FOREIGN KEY (STUDENTID) REFERENCES STUDENT (STUDENTID)
);

CREATE TABLE APPEAL (
    APPEALID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RECORDID NUMBER,
    ENROLLMENTID NUMBER,
    DOCUMENTID NUMBER,
    MESSAGE VARCHAR2(4000),
    DATEFILED DATE,
    STATUS VARCHAR2(20),
    DATEPROCESSED DATE,
    REMARKS VARCHAR2(4000),
    CONSTRAINT FK_APPEAL_RECORD FOREIGN KEY (RECORDID) REFERENCES RECORD (RECORDID),
    CONSTRAINT FK_APPEAL_ENROLLMENT FOREIGN KEY (ENROLLMENTID) REFERENCES ENROLLMENT (ENROLLMENTID),
    CONSTRAINT FK_APPEAL_DOCUMENT FOREIGN KEY (DOCUMENTID) REFERENCES DOCUMENT (DOCUMENTID)
);

CREATE TABLE REQUEST (
    REQUESTID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLOYEEID VARCHAR2(20) NOT NULL,
    DETAILS VARCHAR2(500) NOT NULL,
    MESSAGE VARCHAR2(4000) NOT NULL,
    TYPE VARCHAR2(50) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    DATEFILED TIMESTAMP,
    DATEPROCESSED TIMESTAMP,
    REMARKS VARCHAR2(4000)
);

CREATE TABLE GENERATEDSUGGESTION (
    GENERATEDSUGGESTIONID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SUGGESTIONID NUMBER,
    DOCUMENTID NUMBER,
    GENERATEDTEXT CLOB,
    GENERATEDAT TIMESTAMP,
    CONSTRAINT FK_GENSUGGESTION_SUGGESTION FOREIGN KEY (SUGGESTIONID) REFERENCES SUGGESTION (SUGGESTIONID),
    CONSTRAINT FK_GENSUGGESTION_DOCUMENT FOREIGN KEY (DOCUMENTID) REFERENCES DOCUMENT (DOCUMENTID)
);
